"""
Jacobi elliptic functions sn(u|m), cn(u|m), dn(u|m) and Jacobi's epsilon function E(u|m) as SymPy
functions, in the parameter convention m = k² (as in mpmath and DLMF §22).

Derivatives with respect to both arguments are given in closed form; the parameter derivatives
involve u and E(u|m) = ∫_0^u dn²(v|m) dv = E(am(u|m) | m), so that the ring generated by
u, E, sn, cn, dn over the rational functions of m is closed under ∂/∂u and ∂/∂m:
    ∂sn/∂m = cn dn X + sn cn² / (2(1-m)),
    ∂cn/∂m = -sn Φ,
    ∂dn/∂m = -sn² dn / (2(1-m)) - m sn cn X,
    ∂E/∂m  = (E - u)/(2m) + dn Φ,
with X = [(1-m) u - E] / (2m(1-m)) and Φ = ∂am/∂m = dn u/(2m) - dn E/(2m(1-m)) + sn cn/(2(1-m)).
"""
from sympy.core.singleton import S
from sympy.core.function import DefinedFunction, ArgumentIndexError
from sympy.core.expr import Expr
from sympy.functions.elementary.trigonometric import sin, cos
from sympy.functions.elementary.hyperbolic import tanh, sech
from sympy.functions.special.elliptic_integrals import elliptic_k
import mpmath

__all__ = ['jacobi_sn', 'jacobi_cn', 'jacobi_dn', 'jacobi_epsilon']


def _period_index(u, m):
    """u / K(m) if it is an explicit integer (only checked when it can be decided cheaply)."""
    if not (u.is_number and m.is_number) and not u.has(elliptic_k):
        return None
    n = (u / elliptic_k(m)).simplify() if u.has(elliptic_k) else None
    if n is not None and n.is_integer:
        return n
    return None


def _X(u, m):
    return ((1 - m) * u - jacobi_epsilon(u, m)) / (2 * m * (1 - m))


def _dam_dm(u, m):
    sn, cn, dn = jacobi_sn(u, m), jacobi_cn(u, m), jacobi_dn(u, m)
    return dn * u / (2 * m) - dn * jacobi_epsilon(u, m) / (2 * m * (1 - m)) + sn * cn / (2 * (1 - m))


class _JacobiBase(DefinedFunction):
    nargs = 2
    _kind = None

    def _eval_evalf(self, prec):
        u, m = self.args
        if not (u.is_number and m.is_number):
            return None
        with mpmath.workprec(prec):
            val = self._mp(u._to_mpmath(prec), m._to_mpmath(prec))
            if u.is_extended_real and m.is_extended_real:
                val = mpmath.re(val)    # real for real arguments (removes round-off parts)
        return Expr._from_mpmath(val, prec)

    @classmethod
    def _mp(cls, u, m):
        return mpmath.ellipfun(cls._kind, u, m=m)

    def _eval_conjugate(self):
        u, m = self.args
        if m.is_extended_real:
            return self.func(u.conjugate(), m)

    def _eval_is_extended_real(self):
        u, m = self.args
        if u.is_extended_real and m.is_extended_real:
            return True


class jacobi_sn(_JacobiBase):
    """Jacobi elliptic function sn(u|m)."""
    _kind = 'sn'

    @classmethod
    def eval(cls, u, m):
        if u.is_zero:
            return S.Zero
        if m.is_zero:
            return sin(u)
        if m == 1:
            return tanh(u)
        n = _period_index(u, m)
        if n is not None:
            return S.Zero if n % 2 == 0 else (S.One if n % 4 == 1 else S.NegativeOne)
        if u.could_extract_minus_sign():
            return -cls(-u, m)

    def fdiff(self, argindex=1):
        u, m = self.args
        if argindex == 1:
            return jacobi_cn(u, m) * jacobi_dn(u, m)
        if argindex == 2:
            cn = jacobi_cn(u, m)
            return cn * jacobi_dn(u, m) * _X(u, m) + jacobi_sn(u, m) * cn**2 / (2 * (1 - m))
        raise ArgumentIndexError(self, argindex)


class jacobi_cn(_JacobiBase):
    """Jacobi elliptic function cn(u|m)."""
    _kind = 'cn'

    @classmethod
    def eval(cls, u, m):
        if u.is_zero:
            return S.One
        if m.is_zero:
            return cos(u)
        if m == 1:
            return sech(u)
        n = _period_index(u, m)
        if n is not None:
            return (S.One, S.Zero, S.NegativeOne, S.Zero)[int(n % 4)]
        if u.could_extract_minus_sign():
            return cls(-u, m)

    def fdiff(self, argindex=1):
        u, m = self.args
        if argindex == 1:
            return -jacobi_sn(u, m) * jacobi_dn(u, m)
        if argindex == 2:
            return -jacobi_sn(u, m) * _dam_dm(u, m)
        raise ArgumentIndexError(self, argindex)


class jacobi_dn(_JacobiBase):
    """Jacobi elliptic function dn(u|m)."""
    _kind = 'dn'

    @classmethod
    def eval(cls, u, m):
        if u.is_zero or m.is_zero:
            return S.One
        if m == 1:
            return sech(u)
        n = _period_index(u, m)
        if n is not None:
            return S.One if n % 2 == 0 else (1 - m)**S.Half
        if u.could_extract_minus_sign():
            return cls(-u, m)

    def fdiff(self, argindex=1):
        u, m = self.args
        if argindex == 1:
            return -m * jacobi_sn(u, m) * jacobi_cn(u, m)
        if argindex == 2:
            sn, dn = jacobi_sn(u, m), jacobi_dn(u, m)
            return -sn**2 * dn / (2 * (1 - m)) - m * sn * jacobi_cn(u, m) * _X(u, m)
        raise ArgumentIndexError(self, argindex)


class jacobi_epsilon(_JacobiBase):
    """
    Jacobi's epsilon function E(u|m) = ∫_0^u dn²(v|m) dv = E(am(u|m) | m), the incomplete elliptic
    integral of the second kind as a function of u. It is odd in u and quasi-periodic:
    E(u + 2K|m) = E(u|m) + 2E(m).
    """

    @classmethod
    def eval(cls, u, m):
        if u.is_zero:
            return S.Zero
        if m.is_zero:
            return u
        if m == 1:
            return tanh(u)
        if u.could_extract_minus_sign():
            return -cls(-u, m)

    @classmethod
    def _mp(cls, u, m):
        u, m = mpmath.mpmathify(u), mpmath.mpmathify(m)
        if m == 0:
            return u
        if mpmath.im(m) == 0 and mpmath.re(m) < 1:
            # E(u) = Z(u) + (E(m)/K(m)) u with the Jacobi zeta function from θ4
            K = mpmath.ellipk(m)
            q = mpmath.qfrom(m=m)
            z = mpmath.pi * u / (2 * K)
            Z = mpmath.pi / (2 * K) * mpmath.jtheta(4, z, q, 1) / mpmath.jtheta(4, z, q)
            return Z + mpmath.ellipe(m) / K * u
        return mpmath.quad(lambda v: mpmath.ellipfun('dn', v, m=m)**2, [0, u])

    def fdiff(self, argindex=1):
        u, m = self.args
        if argindex == 1:
            return jacobi_dn(u, m)**2
        if argindex == 2:
            return (jacobi_epsilon(u, m) - u) / (2 * m) + jacobi_dn(u, m) * _dam_dm(u, m)
        raise ArgumentIndexError(self, argindex)
